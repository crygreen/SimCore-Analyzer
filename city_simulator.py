import pandas as pd
import json
import os

# 1. Load data directly from the C project folder (auto-path)
csv_path = '../SimCore/simcore_stats.csv'

if not os.path.exists(csv_path):
    print(f"ERROR: Could not find the file at {csv_path}")
    print("Make sure you have run the C simulation at least once.")
    exit(1)

df = pd.read_csv(csv_path)

# 2. Parse timeline (group by Name to get the full route)
timeline_data = []
for name, group in df.groupby('Name'):
    group = group.sort_values('Day')
    # Convert to dict for JSON
    route = group[['Day', 'X', 'Y', 'Mood', 'Money', 'Health', 'MusicSkill']].to_dict('records')
    timeline_data.append({
        'name': name,
        'route': route
    })

timeline_json = json.dumps(timeline_data)

# 3. Load AI dialogues (if generated by ai_engine.py)
dialog_data = None
if os.path.exists('dialogs.json'):
    with open('dialogs.json', 'r', encoding='utf-8') as f:
        dialog_data = json.load(f)
dialog_json = json.dumps(dialog_data) if dialog_data else "null"

# 4. Generate the HTML file
html_template = f"""
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>SimCore Neon City</title>
    <style>
        /* Base layout */
        body {{ 
            margin: 0; 
            padding: 0; 
            background: #050505; 
            color: #fff; 
            font-family: 'Segoe UI', sans-serif; 
            overflow: hidden; 
            display: flex; 
            height: 100vh; 
        }}
        
        /* Sidebar styling */
        #sidebar {{ 
            width: 280px; 
            min-width: 280px; 
            flex-shrink: 0; 
            height: 100%; 
            background: #0a0a0a; 
            border-right: 1px solid #333; 
            padding: 20px; 
            box-sizing: border-box; 
            overflow-y: auto; 
            z-index: 10; 
        }}
        #sidebar h1 {{ 
            font-size: 20px; 
            color: #0ff; 
            text-shadow: 0 0 10px #0ff; 
            text-align: center; 
            margin-top: 0; 
            margin-bottom: 20px; 
        }}
        .citizen-card {{ 
            background: #111; 
            border-radius: 8px; 
            padding: 10px; 
            margin-bottom: 10px; 
            border-left: 4px solid #555; 
            font-size: 13px; 
            transition: 0.3s; 
            box-shadow: 0 0 5px rgba(0,0,0,0.5); 
        }}
        
        /* Map container (holds canvas, controls, and dialogs) */
        .map-container {{ 
            flex-grow: 1; 
            position: relative; 
            display: flex; 
        }}
        canvas {{ 
            width: 100%; 
            height: 100%; 
            display: block; 
        }}

        /* Player Controls */
        .controls {{ 
            position: absolute; 
            bottom: 20px; 
            left: 20px; 
            background: rgba(10,10,10,0.85); 
            padding: 15px; 
            border-radius: 10px; 
            border: 1px solid #0ff; 
            backdrop-filter: blur(5px); 
            display: flex; 
            align-items: center; 
            gap: 15px; 
            z-index: 10; 
        }}
        button {{ 
            background: #0ff; 
            color: #000; 
            border: none; 
            padding: 10px 20px; 
            border-radius: 5px; 
            font-weight: bold; 
            cursor: pointer; 
            box-shadow: 0 0 10px #0ff; 
            transition: 0.2s; 
        }}
        button:hover {{ 
            background: #fff; 
            box-shadow: 0 0 20px #fff; 
        }}
        input[type=range] {{ 
            width: 150px; 
            accent-color: #0ff; 
        }}
        #day-display {{ 
            font-size: 18px; 
            font-weight: bold; 
            color: #f0f; 
            text-shadow: 0 0 10px #f0f; 
        }}
        
        /* AI Dialog Box */
        .dialog-box {{ 
            position: absolute; 
            top: 20px; 
            right: 20px; 
            background: rgba(20,20,20,0.9); 
            border: 2px solid #0ff; 
            border-radius: 10px; 
            padding: 20px; 
            max-width: 400px; 
            box-shadow: 0 0 20px rgba(0,255,255,0.3); 
            display: { 'block' if dialog_data else 'none' }; 
            z-index: 100; 
            backdrop-filter: blur(10px); 
        }}
        .dialog-box h3 {{ 
            margin-top: 0; 
            color: #0ff; 
            text-shadow: 0 0 5px #0ff; 
        }}
        .dialog-box pre {{ 
            margin: 0; 
            color: #ddd; 
            font-family: monospace; 
            white-space: pre-wrap; 
            font-size: 14px; 
        }}
    </style>
</head>
<body>
    <!-- Sidebar for stats -->
    <div id="sidebar">
        <h1>⚡ SIMCORE ⚡</h1>
        <div id="stats-container"></div>
    </div>
    
    <!-- Main Map Area -->
    <div class="map-container">
        <canvas id="cityCanvas"></canvas>
        
        <!-- Player Controls -->
        <div class="controls">
            <button id="playBtn">▶ Play</button>
            <span id="day-display">Day: 0</span>
            <input type="range" id="speedSlider" min="1" max="20" value="5">
            <span>Speed</span>
        </div>
        
        <!-- AI Dialog Overlay -->
        <div class="dialog-box">
            <h3>🤖 AI Event</h3>
            <pre id="dialog-text"></pre>
        </div>
    </div>

    <script>
        const canvas = document.getElementById('cityCanvas');
        const ctx = canvas.getContext('2d');
        const timelineData = {timeline_json};

        // Static map buildings (Must match C code coordinates)
        const homes = [{{x: 100, y: 100}}, {{x: 300, y: 100}}, {{x: 100, y: 500}}, {{x: 300, y: 500}}];
        const works = [{{x: 700, y: 200}}, {{x: 700, y: 400}}];
        const park = {{x: 500, y: 300}};

        // Resize canvas to fit its container
        function resize() {{
            const container = canvas.parentElement;
            canvas.width = container.clientWidth;
            canvas.height = container.clientHeight;
        }}
        window.addEventListener('resize', resize);
        resize();

        // Initialize citizens with starting positions
        const citizens = timelineData.map(c => {{
            const firstPos = c.route[0];
            return {{
                name: c.name,
                route: c.route,
                x: firstPos.X,
                y: firstPos.Y,
                targetX: firstPos.X,
                targetY: firstPos.Y,
                color: '#fff'
            }};
        }});

        // Show AI text if available
        if ({dialog_json}) {{
            document.getElementById('dialog-text').innerText = {dialog_json}.text;
        }}

        // --- DRAWING FUNCTIONS ---
        function drawNeonRect(x, y, w, h, color) {{
            ctx.fillStyle = 'rgba(10,10,10,0.8)';
            ctx.fillRect(x - w/2, y - h/2, w, h);
            ctx.strokeStyle = color;
            ctx.lineWidth = 2;
            ctx.shadowColor = color;
            ctx.shadowBlur = 15;
            ctx.strokeRect(x - w/2, y - h/2, w, h);
            ctx.shadowBlur = 0;
        }}

        function drawCity() {{
            // Background
            ctx.fillStyle = '#050505';
            ctx.fillRect(0, 0, canvas.width, canvas.height);

            // Grid
            ctx.strokeStyle = '#0a1a2a';
            ctx.lineWidth = 1;
            for(let i=0; i<canvas.width; i+=50) {{ ctx.beginPath(); ctx.moveTo(i, 0); ctx.lineTo(i, canvas.height); ctx.stroke(); }}
            for(let i=0; i<canvas.height; i+=50) {{ ctx.beginPath(); ctx.moveTo(0, i); ctx.lineTo(canvas.width, i); ctx.stroke(); }}

            // Draw Buildings
            homes.forEach(h => drawNeonRect(h.x, h.y, 60, 60, '#0055ff')); // Blue Homes
            works.forEach(w => drawNeonRect(w.x, w.y, 100, 80, '#ff00ff')); // Purple Works
            drawNeonRect(park.x, park.y, 80, 80, '#00ff00'); // Green Park

            // Draw Citizens
            citizens.forEach(c => {{
                ctx.beginPath();
                ctx.arc(c.x, c.y, 12, 0, 2 * Math.PI);
                ctx.fillStyle = c.color;
                ctx.shadowColor = c.color;
                ctx.shadowBlur = 20;
                ctx.fill();
                ctx.shadowBlur = 0;

                ctx.font = 'bold 12px Arial';
                ctx.textAlign = 'center';
                ctx.fillStyle = '#fff';
                ctx.fillText(c.name, c.x, c.y - 20);
            }});
        }}

        // --- ANIMATION LOOP ---
        let dayIndex = 0;
        let isPlaying = false;
        let speed = 5;
        let lastTime = 0;
        let timeAccumulator = 0;

        document.getElementById('playBtn').addEventListener('click', (e) => {{
            isPlaying = !isPlaying;
            e.target.innerText = isPlaying ? '⏸ Pause' : '▶ Play';
        }});

        document.getElementById('speedSlider').addEventListener('input', (e) => {{
            speed = parseInt(e.target.value);
        }});

        function updateSidebar() {{
            const statsContainer = document.getElementById('stats-container');
            statsContainer.innerHTML = '';
            citizens.forEach(c => {{
                const pos = c.route[dayIndex];
                statsContainer.innerHTML += `
                    <div class="citizen-card" style="border-left-color: ${{c.color}}; box-shadow: 0 0 10px ${{c.color}}22;">
                        <b style="color: ${{c.color}}">${{c.name}}</b><br>
                        💰 ${{pos.Money}} | ❤️ ${{pos.Health}}<br>
                        😊 ${{pos.Mood}} | 🎵 ${{pos.MusicSkill}}
                    </div>
                `;
            }});
        }}

        function update(time) {{
            const deltaTime = time - lastTime;
            lastTime = time;

            if (isPlaying) {{
                timeAccumulator += deltaTime;
                // Time delay between days based on speed slider
                if (timeAccumulator > (1000 / speed)) {{
                    timeAccumulator = 0;
                    dayIndex++;
                    
                    // Loop timeline
                    if (dayIndex >= citizens[0].route.length) dayIndex = 0; 

                    // Update target coordinates and colors
                    citizens.forEach(c => {{
                        const pos = c.route[dayIndex];
                        c.targetX = pos.X;
                        c.targetY = pos.Y;
                        
                        let m = pos.Mood;
                        c.color = m > 70 ? '#00ffcc' : (m > 40 ? '#ffaa00' : '#ff0044');
                    }});
                    
                    document.getElementById('day-display').innerText = 'Day: ' + citizens[0].route[dayIndex].Day;
                    updateSidebar();
                }}
            }}

            // Smooth movement (lerp)
            citizens.forEach(c => {{
                c.x += (c.targetX - c.x) * 0.08; 
                c.y += (c.targetY - c.y) * 0.08;
            }});

            drawCity();
            requestAnimationFrame(update);
        }}

        // Start animation
        lastTime = performance.now();
        updateSidebar();
        requestAnimationFrame(update);
    </script>
</body>
</html>
"""

with open('city_simulator.html', 'w', encoding='utf-8') as file:
    file.write(html_template)

print("Visualizer updated with fixed layout and auto-paths.")